# refresh.ps1 -- hunt for new / better links and rewrite live.txt
#
#   Double-click REFRESH.bat  (or: powershell -File refresh.ps1)
#
# What it does:
#   1. re-downloads the public iptv-org playlists, pulls every NFL channel
#   2. scans a handful of streaming sites for raw .m3u8 URLs
#   3. probes every candidate (resolution + real throughput)
#   4. writes the winners to live.txt, sorted best-first
# play.ps1 always reads live.txt before feeds.txt, so new finds get used first.
param([switch]$Quiet)

$ErrorActionPreference = 'SilentlyContinue'
$ProgressPreference    = 'SilentlyContinue'
$root    = $PSScriptRoot
$relayPy = Join-Path $root 'relay.py'
$liveOut = Join-Path $root 'live.txt'
$srcDir  = Join-Path $root '_src'
$UA      = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0 Safari/537.36'

function Say($m, $c = 'Gray') { Write-Host $m -ForegroundColor $c }
New-Item -ItemType Directory -Force -Path $srcDir | Out-Null

function Find-Python {
    $c = Get-Command python -ErrorAction SilentlyContinue
    if ($c) { return $c.Source }
    $c = Get-Command py -ErrorAction SilentlyContinue
    if ($c) { return $c.Source }
    return $null
}
$py = Find-Python

function Probe([string]$url) {
    if (-not $py) { return $null }
    $out = & $py $relayPy --url $url --probe-only 2>&1
    if ($LASTEXITCODE -ne 0) { return $null }
    $line = ($out | Where-Object { $_ -match '^\s*\{.*\}\s*$' } | Select-Object -Last 1)
    if (-not $line) { return $null }
    try { return ($line | ConvertFrom-Json) } catch { return $null }
}

$cands = @()   # @{name, url}

# ---- 1. public iptv-org playlists: every NFL-flavoured channel ----
Say '  [1/3] pulling public channel lists...' 'Cyan'
$lists = @{
    'sports.m3u' = 'https://iptv-org.github.io/iptv/categories/sports.m3u'
    'us.m3u'     = 'https://iptv-org.github.io/iptv/countries/us.m3u'
    'index.m3u'  = 'https://iptv-org.github.io/iptv/index.m3u'
}
foreach ($k in $lists.Keys) {
    $f = Join-Path $srcDir $k
    & curl.exe -sL -m 45 -A $UA -o $f $lists[$k]
}

foreach ($f in (Get-ChildItem $srcDir -Filter '*.m3u')) {
    $name = ''
    foreach ($line in (Get-Content $f.FullName -Encoding UTF8)) {
        if ($line -match '^#EXTINF') { $name = $line; continue }
        if ($line -match '^https?://' -and $name) {
            if ($name -match '(?i)\bNBA\b') {
                $label = ($name -split ',')[-1].Trim()
                $cands += [pscustomobject]@{ Name = "$label [$($f.BaseName)]"; Url = $line.Trim() }
            }
            $name = ''
        }
    }
}
Say ("        {0} NFL entries found" -f $cands.Count) 'DarkGray'

# ---- 2. scrape sites listed in sites.txt for raw m3u8 URLs ----
$siteFile = Join-Path $root 'sites.txt'
if (Test-Path $siteFile) {
    Say '  [2/3] scanning streaming sites for raw .m3u8...' 'Cyan'
    $pages = Get-Content $siteFile -Encoding UTF8 | Where-Object { $_ -match '^https?://' }
    foreach ($pg in $pages) {
        $html = & curl.exe -sL -m 15 -A $UA $pg 2>$null
        if (-not $html) { continue }
        $found = [regex]::Matches(($html -join "`n"), 'https?://[^"''<>\\\s]+\.m3u8[^"''<>\\\s]*')
        foreach ($m in $found) {
            $cands += [pscustomobject]@{ Name = "scraped [$(([uri]$pg).Host)]"; Url = $m.Value }
        }
    }
    Say ("        {0} candidates total" -f $cands.Count) 'DarkGray'
}

# ---- 3. probe everything ----
Say '  [3/3] probing (this takes a minute)...' 'Cyan'
$seen = @{}
$good = @()
foreach ($c in $cands) {
    if ($seen.ContainsKey($c.Url)) { continue }
    $seen[$c.Url] = 1
    $p = Probe $c.Url
    if (-not $p) { continue }
    if ($p.h -lt 720) { continue }
    $good += [pscustomobject]@{ Name = $c.Name; Url = $c.Url; H = $p.h; W = $p.w; BW = $p.bw_mbps; FPS = $p.fps; Speed = $p.fetch_Mbps }
}

$good = $good | Sort-Object -Property @{e='H'}, @{e='BW'} -Descending

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('# live.txt -- auto-generated by refresh.ps1 on ' + (Get-Date -Format 'yyyy-MM-dd HH:mm'))
$lines.Add('# play.ps1 reads this BEFORE feeds.txt. Delete this file anytime.')
$lines.Add('#')
foreach ($g in $good) {
    $lines += ('{0,-42} | {1}' -f ("{0}  ({1}x{2}@{3})" -f $g.Name, $g.W, $g.H, $g.BW), $g.Url)
}
Set-Content -LiteralPath $liveOut -Value $lines -Encoding UTF8

Say ''
if ($good.Count -gt 0) {
    Say ("  {0} working links saved to live.txt:" -f $good.Count) 'Green'
    foreach ($g in $good) { Say ("    {0,5}x{1,-7} {2,6:N1} Mbps  {3}" -f $g.W, $g.H, $g.BW, $g.Name) 'Gray' }
} else {
    Say '  No new links passed. Existing feeds.txt still works.' 'Yellow'
}
Say ''
if (-not $Quiet) { Read-Host 'Press Enter to close' | Out-Null }
